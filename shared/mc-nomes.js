export function mcNorm(texto) {
  return String(texto ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[_\-\s]+/g, ' ')
    .trim();
}

const POR_NOME_PT = new Map();
for (const [chave, pt] of Object.entries(MC_NOMES_PT)) {
  const norm = mcNorm(pt);
  if (norm && !POR_NOME_PT.has(norm)) POR_NOME_PT.set(norm, chave);
}

