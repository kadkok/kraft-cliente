export function mcNomePt(chaveOuEstado) {
  let chave = '';
  if (typeof chaveOuEstado === 'number') {
    if (chaveOuEstado >= MC_BASE) chave = mcEstado(chaveOuEstado - MC_BASE)?.nome || '';
  } else {
    chave = String(chaveOuEstado || '');
  }
  if (!chave) return '';
  return MC_NOMES_PT[chave] || chave.replace(/_/g, ' ');
}

export function mcChavePorNome(texto) {
  const q = mcNorm(texto);
  return q ? (POR_NOME_PT.get(q) || '') : '';
}

export function mcCombina(chave, busca) {
  const q = mcNorm(busca);
  if (!q) return true;
  if (mcNorm(MC_NOMES_PT[chave] || '').includes(q)) return true;
  if (mcNorm(chave).includes(q)) return true;
  return Boolean(ALIAS_BUSCA[chave]?.includes(q));
}
